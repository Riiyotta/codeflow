#!/usr/bin/env python3
"""Generate tokens/llm/token-catalog.json from the real token files: every token path, its category, its
resolved value, its evidence id (and status / assetRole / sourceName where the token file records them),
plus the themes (which semantic tokens each theme resolves, and to what) and the typography-role ids.

extraction/verify_all.py rebuilds the catalog in memory and fails if the file on disk differs, so neither the
catalog nor a token file can be edited alone. Run: python3 tokens/build_catalog.py [--check]
"""
import glob
import json
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokens_lib as T  # noqa: E402

OUT = os.path.join(T.TOKENS, "llm", "token-catalog.json")
VERSION = "1.0.0"

# Category by the first path segment; typography and motion hold several kinds and are split by the second.
ROOT_CATEGORY = {
    "color": "color", "spacing": "spacing", "radius": "radius", "breakpoint": "breakpoint",
    "layer": "layer", "iconSize": "iconSize", "semantic": "semanticColor", "component": "component", "layout": "layout",
}
TYPOGRAPHY = {"fontFamily": "fontFamily", "fontWeight": "fontWeight", "role": "typography"}


def category(path):
    parts = path.split(".")
    if parts[0] == "typography":
        return TYPOGRAPHY[parts[1]]
    if parts[0] == "motion":
        return "motion"
    if path == "breakpoint.deviceDetection":
        return "motion"   # the user-agent motion-mode flag; it is about motion, not about widths
    return ROOT_CATEGORY[parts[0]]


def build(tokens_dir=None):
    base = tokens_dir or T.TOKENS
    tree, _ = T.load_tree(base)
    tokens = {}
    for path, node in T.walk_tokens(tree):
        if path in tokens:
            raise ValueError("duplicate token path " + path)
        entry = {"category": category(path), "value": T.resolve_value(tree, node), "evidence": node["evidence"]}
        for k in ("status", "assetRole", "sourceName"):
            if k in node:
                entry[k] = node[k]
        tokens[path] = entry
    counts = {}
    for t in tokens.values():
        counts[t["category"]] = counts.get(t["category"], 0) + 1
    themes = {}
    for f in sorted(glob.glob(os.path.join(base, "themes", "*.json"))):
        with open(f, encoding="utf-8") as fh:
            d = json.load(fh)
        resolves = {"semantic." + k: v for k, v in d["resolves"].items()}
        themes[d["theme"]] = {"file": "tokens/themes/" + os.path.basename(f), "semanticTokens": sorted(resolves), "resolves": dict(sorted(resolves.items()))}
    roles = sorted(tree["typography"]["role"])
    return {
        "version": VERSION,
        "$comment": "GENERATED by tokens/build_catalog.py from tokens/{00-foundation,10-semantic,20-component,30-layout,themes}. Do not hand-edit; extraction/verify_all.py rebuilds it and fails on any difference. A PageSpec names tokens by these paths, never by raw values.",
        "counts": {"tokens": len(tokens), "byCategory": dict(sorted(counts.items())), "themes": len(themes), "typographyRoles": len(roles)},
        "themes": themes,
        "typographyRoles": roles,
        "tokens": dict(sorted(tokens.items())),
    }


def render(catalog):
    return json.dumps(catalog, indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    text = render(build())
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("catalog up to date" if ok else "catalog OUT OF DATE")
        sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote tokens/llm/token-catalog.json")
